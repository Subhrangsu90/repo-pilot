import { Component, computed, inject, linkedSignal } from '@angular/core';
import { valueOf } from '../../core/resource';
import { EmitFn } from '@repopilot/shared';
import { AgentSession } from '../../core/agent-session';
import { ServerStatus } from '../../core/server-status';
import { StepTimeline } from '../../genui/components/step-timeline';
import { GenUiHost } from '../../genui/genui-host';

/** Surfaces built by the server that carry their own frame and badge. */
const GATES = new Set(['ApprovalCard', 'PrReview', 'ReleaseForm']);

/** "v1.0.0" → "v1.1.0": the next minor version, keeping the "v" prefix. */
export function nextMinor(tag: string | null | undefined): string {
  const m = /^(v?)(\d+)\.(\d+)\.\d+/.exec(tag ?? '');
  return m ? `${m[1]}${m[2]}.${Number(m[3]) + 1}.0` : 'v0.1.0';
}

/**
 * Screen Spec "Release builder": ask the agent for a release, then edit its
 * draft beside a live preview and publish. Runs its own agent conversation,
 * separate from Ask.
 */
@Component({
  selector: 'app-release-builder',
  imports: [GenUiHost, StepTimeline],
  providers: [AgentSession],
  host: { class: 'block' },
  template: `
    <div class="mx-auto flex w-full max-w-[1280px] flex-col gap-6 px-4 py-8 sm:px-8">
      <div class="flex flex-col gap-1.5">
        <h1 class="font-display text-h1">Releases</h1>
        <p class="max-w-3xl text-body text-fg-muted">
          The agent drafts release notes from the pull requests merged since the last release. You edit them beside a
          preview and publish; nothing reaches GitHub before that.
        </p>
      </div>

      @if (canAsk()) {
        <form
          class="flex max-w-[720px] items-end gap-3 rounded-lg border border-border-strong bg-surface-1 py-2.5 pr-2.5 pl-4.5 focus-within:outline-2 focus-within:outline-offset-2 focus-within:outline-focus"
          (submit)="submit($event)"
        >
          <label for="release-prompt" class="sr-only">What release should the agent draft?</label>
          <input
            #box
            id="release-prompt"
            class="h-11 min-w-0 flex-1 bg-transparent text-body text-fg outline-none placeholder:text-fg-faint"
            maxlength="300"
            [value]="draft()"
            (input)="draft.set(box.value)"
          />
          <button type="submit" class="btn btn-primary" [disabled]="!draft().trim()">Draft release</button>
        </form>
      }

      @if (turn(); as t) {
        <div class="flex flex-col gap-5" aria-live="polite">
          <p class="ml-auto max-w-[min(520px,85%)] rounded-lg rounded-br-sm bg-surface-3 px-4 py-3 text-body">{{ t.prompt }}</p>

          @if (t.steps.length) {
            <app-step-timeline [props]="{ steps: t.steps }" [inline]="true" />
          }

          @for (surface of t.surfaces; track surface.surfaceId) {
            @if (isGate(surface.node)) {
              <app-genui-host class="animate-genui-enter" [node]="surface.node" [emit]="onEmit" />
            } @else {
              <section class="agent-surface flex animate-genui-enter flex-col gap-4 p-4 sm:p-6" aria-label="Generated by the agent">
                <app-genui-host [node]="surface.node" [emit]="onEmit" />
              </section>
            }
          }

          @if (t.status === 'running' && t.surfaces.length === 0) {
            <div class="flex flex-wrap items-start gap-5" aria-hidden="true">
              <div class="h-[28rem] min-w-0 flex-[3_1_460px] animate-pulse rounded-xl bg-surface-3"></div>
              <div class="h-80 min-w-0 flex-[2_1_300px] animate-pulse rounded-xl bg-surface-3"></div>
            </div>
          }

          @if (t.actionError) {
            <p class="card border-danger px-4 py-3 text-body-sm" role="alert">Your decision was not sent: {{ t.actionError }}</p>
          }
          @if (t.text) {
            <p class="max-w-[680px] text-body whitespace-pre-line text-fg-muted">{{ t.text }}</p>
          }
          @if (t.status === 'error') {
            <p class="card border-danger p-4 text-body-sm" role="alert">{{ t.error }}</p>
          }
        </div>
      }
    </div>
  `,
})
export class ReleaseBuilder {
  protected readonly session = inject(AgentSession);
  private readonly status = inject(ServerStatus);

  /** Starts as "Draft release v1.1.0 from everything since v1.0.0", from the latest release. */
  protected readonly draft = linkedSignal(() => {
    const latest = valueOf(this.status.overview)?.latestRelease;
    return latest ? `Draft release ${nextMinor(latest)} from everything since ${latest}` : 'Draft the first release';
  });
  protected readonly turn = computed(() => this.session.turns().at(-1));
  protected readonly canAsk = computed(() => !this.session.isBusy() && !this.session.awaitingApproval());
  protected readonly onEmit: EmitFn = this.session.handleUiEvent;

  protected isGate(node: unknown) {
    return GATES.has(String((node as { component?: unknown } | null)?.component));
  }

  protected submit(event: Event) {
    event.preventDefault();
    const prompt = this.draft().trim().slice(0, 2000);
    if (!prompt || !this.canAsk()) return;
    this.session.reset();
    void this.session.send(prompt);
  }
}
